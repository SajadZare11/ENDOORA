export const CONCEPT_MAP: Record<string, DktConcept> = AEF_60_CONCEPTS.reduce(
  (acc, c) => {
    acc[c.id] = c;
    return acc;
  },
  {} as Record<string, DktConcept>
);

/**
 * Resolves a DktConcept from level and stage number.
 */
export function getConceptByStage(cefr: CefrLevel, stageNumber: number): DktConcept | undefined {
  const targetId = `${cefr.toLowerCase()}-${String(stageNumber).padStart(2, "0")}`;
  return CONCEPT_MAP[targetId];
}

/**
 * Fuzzy matches a circuit's targetConcept string to the closest DktConcept.
 */
export function findClosestConcept(
  cefr: CefrLevel,
  stageNumber: number,
  targetConceptText?: string
): DktConcept {
  const direct = getConceptByStage(cefr, stageNumber);
  if (direct) return direct;
  return AEF_60_CONCEPTS[0];
}
