// Generates starter levels for A2 through C2
function generatePlaceholderLevels(skill: SkillKey, cefr: CefrLevel, themeFa: string): GameLevel[] {
  const levels: GameLevel[] = [];
  for (let i = 1; i <= 10; i++) {
    levels.push({
      levelNumber: i,
      cefr,
      skill,
      titleFa: `مرحله ${i}: ${themeFa}`,
      titleEn: `${cefr} Level ${i}: ${skill.toUpperCase()} Mastery`,
      descriptionFa: `چالش تخصصی مرحله ${i} از سطح ${cefr} برای تسلط به مهارت ${skill}.`,
      xpReward: 50 + i * 5,
      timeLimitSeconds: 50,
      questions: [
        {
          id: `${skill[0]}-${cefr.toLowerCase()}-${i}-1`,
          type: "vocab-blitz",
          prompt: `چالش مرحله ${i} سطح ${cefr} (${skill})`,
          promptFa: `پاسخ صحیح چالش مهارت ${skill} در سطح ${cefr} را برگزینید.`,
          options: ["گزینه اول (درست)", "گزینه دوم", "گزینه سوم", "گزینه چهارم"],
          correctAnswer: 0,
          explanationFa: `نکته آموزشی سطح ${cefr} برای مرحله ${i}.`,
        },
      ],
    });
  }
  return levels;
}

export function getSkillLevels(skill: SkillKey, cefr: CefrLevel): GameLevel[] {
  return SKILLS_GAME_DATA[skill]?.[cefr] || [];
}

export function getSkillLevel(skill: SkillKey, cefr: CefrLevel, levelNum: number): GameLevel | undefined {
  const levels = getSkillLevels(skill, cefr);
  return levels.find((l) => l.levelNumber === levelNum);
}
