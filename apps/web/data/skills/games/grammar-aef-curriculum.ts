import { GRAMMAR_SENTENCE_BANK } from "./grammar-sentence-bank.ts";
import { GRAMMAR_EXPANDED_BANK } from "./grammar-expanded-bank.ts";

export function getGrammarStageData(cefr: CefrLevel, levelNumber: number): GrammarStageData | null {
  const baseStage = GRAMMAR_AEF_CURRICULUM[cefr]?.[levelNumber];
  if (!baseStage) return null;

  const bankCircuits = GRAMMAR_SENTENCE_BANK[cefr]?.[levelNumber] || [];
  const expandedCircuits = GRAMMAR_EXPANDED_BANK[cefr]?.[levelNumber] || [];
  const allCircuits = [...baseStage.circuits, ...bankCircuits, ...expandedCircuits];

  return {
    ...baseStage,
    circuits: allCircuits.length > 0 ? allCircuits : baseStage.circuits,
  };
}
