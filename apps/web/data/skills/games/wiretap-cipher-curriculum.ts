export function getWiretapStage(cefr: string, levelNumber: number): WiretapStage | undefined {
  const validCefr = ["A1", "A2", "B1", "B2", "C1", "C2"];
  if (!validCefr.includes(cefr)) {
    return undefined;
  }
  const stages = WIRETAP_CURRICULUM[cefr as "A1" | "A2" | "B1" | "B2" | "C1" | "C2"];
  return stages?.find((s) => s.levelNumber === levelNumber);
}
