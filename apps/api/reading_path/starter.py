    items = []
    for index, (
        stage,
        skill,
        passage,
        prompt,
        choices,
        key,
        evidence,
        reasons,
    ) in enumerate(DATA, 1):
        fields = {"option_" + k: v for k, v in zip("abc", choices)}
        fields.update({"reason_" + k: v for k, v in zip("abc", reasons)})
        items.append(
            Item(
                edition=edition,
                code=f"{stage}-{index:02}",
                stage=stage,
                skill=skill,
                passage=passage,
                prompt=prompt,
                key=key,
                evidence=evidence,
                **fields,
            )
        )
    Item.objects.bulk_create(items)
